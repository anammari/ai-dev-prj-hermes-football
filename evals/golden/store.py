"""Write a finished run to Postgres, exactly once.

This is the only writer of `eval_runs` / `eval_results`, and it uses the owner URL - the same split
the migrations and the ingestion pipeline use. It is not reachable from the API: the request path
reads these tables through `agent_readonly` and has no write engine for them.

The run id is generated by the caller, so an artifact and its row share one identity. A replayed id is
refused rather than silently duplicated: two rows with the same id would make the scoreboard count a
run twice.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy.orm import Session, sessionmaker

from db.models import EvalResult, EvalRun, new_id
from db.session import create_db_engine
from db.settings import Settings


def store_run(settings: Settings, run: dict, records: list[dict]) -> None:
    """Insert the run and one row per question. Raises if the run already exists."""
    engine = create_db_engine(settings)
    try:
        factory = sessionmaker(bind=engine, expire_on_commit=False, future=True)
        with factory() as session:
            _insert(session, run, records)
    finally:
        engine.dispose()


def _insert(session: Session, run: dict, records: list[dict]) -> None:
    if session.get(EvalRun, run["run_id"]) is not None:
        raise ValueError(f"eval run {run['run_id']} is already stored")
    session.add(
        EvalRun(
            id=run["run_id"],
            set_name=run["set_name"],
            golden_set_sha256=run["golden_set_sha256"],
            prompt_version=run["prompt_version"],
            model=run["model"],
            git_commit=run["git_commit"],
            source=run["source"],
            status=run["status"],
            passed=bool(run["passed"]),
            metrics=run["metrics"],
            failure_reasons=list(run["failure_reasons"]),
            started_at=_datetime(run["started_at"]),
            finished_at=_datetime(run["finished_at"]),
        )
    )
    session.flush()  # the results carry a foreign key and there is no relationship() to order them
    session.add_all(
        [
            EvalResult(
                id=new_id(),
                run_id=run["run_id"],
                question_id=str(record["id"]),
                class_name=str(record["class"]),
                expected_route=str(record["expected_route"]),
                expected_tool=record.get("expected_tool"),
                route=record.get("route"),
                tool=record.get("tool"),
                retrieved=_retrieved(record),
                scores=record.get("scores") or {},
                latency_ms=record.get("latency_ms"),
                error=record.get("error"),
            )
            for record in records
        ]
    )
    session.commit()


def _retrieved(record: dict) -> list[dict] | None:
    """What the answer was grounded on, in the contract's open-object shape.

    A knowledge question stores its passages (file, heading, score); a database question stores which
    tools ran and what data timestamp they carried. Storing the payloads themselves would copy the
    database into the eval table for no reader's benefit.
    """
    evidence = record.get("evidence") or {}
    hits = (evidence.get("search_knowledge") or {}).get("hits") or []
    if hits:
        return [
            {
                "source_file": hit.get("source_file"),
                "heading": hit.get("heading"),
                "score": hit.get("score"),
            }
            for hit in hits
        ]
    tools = [
        {"tool": name, "data_as_of": (payload or {}).get("data_as_of")}
        for name, payload in evidence.items()
        if name != "search_knowledge"
    ]
    return tools or None


def _datetime(value) -> datetime:
    return value if isinstance(value, datetime) else datetime.fromisoformat(str(value))
